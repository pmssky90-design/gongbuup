from __future__ import annotations

import json
from itertools import product
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
POOL_DIR = ROOT / "data" / "sentence_pools"


def make(prefix: str, count: int, starts: list[str], middles: list[str], ends: list[str]) -> list[dict[str, str]]:
    texts: list[str] = []
    for start, middle, end in product(starts, middles, ends):
        text = f"{start} {middle} {end}".strip()
        if text not in texts:
            texts.append(text)
        if len(texts) == count:
            break
    if len(texts) < count:
        raise ValueError(f"{prefix}: 필요한 {count}개 문장을 만들 수 없습니다.")
    return [{"id": f"{prefix}_{index:03d}", "text": text} for index, text in enumerate(texts, start=1)]


def write_pool(filename: str, prefix: str, count: int, starts: list[str], middles: list[str], ends: list[str]) -> None:
    path = POOL_DIR / filename
    payload = make(prefix, count, starts, middles, ends)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


